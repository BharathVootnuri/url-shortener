-- V1: core schema. Written in the SQL subset shared by PostgreSQL and H2 (PostgreSQL mode).

CREATE TABLE short_link (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(16)   NOT NULL,
    original_url  VARCHAR(2048) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at    TIMESTAMP WITH TIME ZONE,
    click_count   BIGINT        NOT NULL DEFAULT 0,
    -- Uniqueness is enforced by the database, not just application logic (NFR-3).
    -- This also creates the index used by redirect lookups.
    CONSTRAINT uk_short_link_code UNIQUE (code)
);

CREATE TABLE click_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    short_link_id  BIGINT       NOT NULL,
    clicked_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    referrer       VARCHAR(512),
    user_agent     VARCHAR(512),
    -- Intentionally no IP address column (privacy, see D7).
    CONSTRAINT fk_click_event_short_link
        FOREIGN KEY (short_link_id) REFERENCES short_link (id) ON DELETE CASCADE
);

-- Supports per-link analytics queries bounded by a time range.
CREATE INDEX idx_click_event_link_time ON click_event (short_link_id, clicked_at);
